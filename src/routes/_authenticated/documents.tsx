import { createFileRoute } from "@tanstack/react-router";
import { useQuery, useQueryClient } from "@tanstack/react-query";
import { Download, Trash2 } from "lucide-react";
import { toast } from "sonner";
import { PageHeader, Panel, DataTable, EmptyState } from "@/components/app/ui";
import { Button } from "@/components/ui/button";
import { AlertDialog, AlertDialogAction, AlertDialogCancel, AlertDialogContent, AlertDialogDescription, AlertDialogFooter, AlertDialogHeader, AlertDialogTitle, AlertDialogTrigger } from "@/components/ui/alert-dialog";
import { supabase } from "@/integrations/supabase/client";
import { downloadFromStorage, fmtDate, logActivity, meQuery } from "@/lib/data";
import { downloadBlob, safeFileName } from "@/lib/generate";
import { pageHead } from "@/lib/seo";

export const Route = createFileRoute("/_authenticated/documents")({
  head: () => pageHead("Generated Documents", "Browse and download generated documents."),
  component: Documents,
});

function Documents() {
  const qc = useQueryClient();
  const { data: me } = useQuery(meQuery);
  const { data: docs, isLoading } = useQuery({
    queryKey: ["documents"],
    queryFn: async () => {
      const [{ data: d }, { data: p }] = await Promise.all([
        supabase.from("generated_documents").select("*").order("created_at", { ascending: false }).limit(500),
        supabase.from("profiles").select("id,full_name,email"),
      ]);
      const names = new Map((p ?? []).map((x) => [x.id, x.full_name || x.email]));
      return (d ?? []).map((x) => ({ ...x, by: names.get(x.generated_by) ?? "—" }));
    },
  });

  async function download(path: string, title: string, format: string) {
    try { downloadBlob(await downloadFromStorage("generated", path), `${safeFileName(title)}.${format}`); }
    catch (e) { toast.error(e instanceof Error ? e.message : "Download failed"); }
  }
  async function remove(id: string, path: string, title: string) {
    const { error } = await supabase.from("generated_documents").delete().eq("id", id);
    if (error) return toast.error(error.message);
    await supabase.storage.from("generated").remove([path]);
    await logActivity("Deleted document", "document", id, { title });
    toast.success("Document deleted");
    qc.invalidateQueries({ queryKey: ["documents"] });
  }

  return (
    <>
      <PageHeader title="Generated Documents" description={me?.isAdmin ? "Every document created by your team." : "Documents you have generated."} />
      <Panel>
        {!isLoading && docs?.length === 0 ? <EmptyState title="No documents yet" text="Generated documents are stored securely and listed here." /> : (
          <DataTable
            head={["Document", "Template", "Format", "Generated by", "Created", ""]}
            rows={(docs ?? []).map((d) => [
              <span className="font-medium">{d.title}</span>, d.template_name, d.format.toUpperCase(), d.by, fmtDate(d.created_at),
              <div className="flex justify-end gap-1">
                <Button size="sm" variant="outline" onClick={() => download(d.storage_path, d.title, d.format)}><Download /> Download</Button>
                {me?.isAdmin && (
                  <AlertDialog>
                    <AlertDialogTrigger asChild><Button size="sm" variant="ghost" aria-label="Delete"><Trash2 /></Button></AlertDialogTrigger>
                    <AlertDialogContent>
                      <AlertDialogHeader><AlertDialogTitle>Delete this document?</AlertDialogTitle>
                        <AlertDialogDescription>"{d.title}" and its stored file will be permanently removed.</AlertDialogDescription></AlertDialogHeader>
                      <AlertDialogFooter><AlertDialogCancel>Cancel</AlertDialogCancel>
                        <AlertDialogAction onClick={() => remove(d.id, d.storage_path, d.title)}>Delete</AlertDialogAction></AlertDialogFooter>
                    </AlertDialogContent>
                  </AlertDialog>
                )}
              </div>,
            ])}
          />
        )}
      </Panel>
    </>
  );
}
